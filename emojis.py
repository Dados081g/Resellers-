"""
Premium-эмодзи (tg-emoji).

ВАЖНО: Telegram позволяет вставлять кастомные premium-эмодзи только через
HTML parse_mode тегом <tg-emoji emoji-id="ID">обычный_эмодзи</tg-emoji>.
Обычный эмодзи внутри тега — это "фолбэк", который увидят пользователи без
Telegram Premium (кастомная картинка увидят только у кого Premium есть).

Как достать custom_emoji_id под свой вкус:
1. Запусти бота, дай себе права админа (ADMIN_IDS в config.py).
2. Отправь боту сообщение, полностью состоящее из нужных premium-эмодзи
   (просто скопируй их из любого премиум-чата/эмодзи-панели).
3. Ответь на это сообщение командой /getemoji — бот пришлёт тебе готовые
   custom_emoji_id для каждого эмодзи по порядку.
4. Подставь ID сюда, в словарь EMOJI ниже.

Ниже — placeholder ID (это реальные системные id некоторых стандартных
premium-паков, но лучше замени их своими через /getemoji, чтобы стиль
совпадал с твоим оформлением).
"""

